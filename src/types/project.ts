/** Один медиафайл карточки. */
export type ProjectMedia =
  | { type: 'image'; src: string; alt?: string }
  | { type: 'video'; src: string }

export interface Project {
  id: string
  /** Заголовок карточки — показывается капсом. */
  title: string
  /** Где проходил проект — показывается второй строкой под заголовком. */
  location?: string
  /** Подпись: техника, площадка, год. */
  subtitle?: string
  /** Соотношение сторон карточки (ширина / высота) для masonry-сетки. */
  aspectRatio: number
  /**
   * Медиа проекта. Если есть видео — оно играет само, когда карточка на экране,
   * а при ховере показывается первое фото. Если только фото — при ховере
   * они перелистываются по очереди. Первое фото — обложка.
   */
  media: ProjectMedia[]
}
